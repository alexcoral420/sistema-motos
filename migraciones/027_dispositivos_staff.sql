-- Suscripciones Web Push del staff (gerencia/admin) para los avisos del
-- panel (Fase B1: solo la suscripción; el envío llega en B2).
--
-- Separada de 'dispositivos' (023), que es del motero: aquella cuelga de
-- perfiles (Supabase Auth) y la alcanza 'authenticated' por RLS; esta
-- cuelga de usuarios (el panel) y SOLO la alcanza service_role. RLS
-- activado sin políticas: anon y authenticated no ven ni una fila.
--
-- suscripcion la valida y reconstruye el servidor antes de guardarla
-- (app/seguridad/suscripcion_push.py: endpoint https de un servicio de
-- push conocido, para que el envío no sea un vector de SSRF).
-- endpoint se deriva de la suscripción: con UNIQUE (usuario_id, endpoint),
-- volver a activar en el mismo navegador actualiza y reactiva la fila en
-- vez de duplicarla.

CREATE TABLE IF NOT EXISTS dispositivos_staff (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id   bigint NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    suscripcion  jsonb NOT NULL,
    endpoint     text GENERATED ALWAYS AS (suscripcion ->> 'endpoint') STORED,
    activo       boolean NOT NULL DEFAULT true,
    creado_en    timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT dispositivos_staff_usuario_endpoint_unico UNIQUE (usuario_id, endpoint),
    CONSTRAINT dispositivos_staff_con_endpoint CHECK (suscripcion ? 'endpoint')
);

-- B2: un 404/410 del servicio de push desactiva ese endpoint.
CREATE INDEX IF NOT EXISTS dispositivos_staff_endpoint_idx ON dispositivos_staff (endpoint);

ALTER TABLE dispositivos_staff ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON dispositivos_staff FROM anon;
REVOKE ALL ON dispositivos_staff FROM authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON dispositivos_staff TO service_role;

notify pgrst, 'reload schema';
