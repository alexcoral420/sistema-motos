-- "Mi espacio" del motero, Capa 0: cuentas + motos.
--
-- Las cuentas viven en Supabase Auth (auth.users). Aquí se agregan:
--   - perfiles: datos del motero, 1 a 1 con auth.users.
--   - motos_usuario: las motos que el motero registra como suyas.
--
-- A diferencia del resto del esquema (service_role desde el servidor), estas
-- tablas se consultan con la llave anon + el JWT del motero: RLS es la
-- barrera real. Cada motero solo ve y toca sus propias filas.
--
-- Consentimiento: politica_id / version_politica NO los escribe el motero.
-- Los estampa el trigger handle_new_user() al crear la cuenta, leyendo la
-- política vigente, y solo si el registro trajo acepta_politica = true en
-- el metadata. El motero no tiene GRANT de UPDATE sobre esas columnas, así
-- que no puede reescribir a qué versión consintió.

CREATE TABLE IF NOT EXISTS perfiles (
    id                uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    nombre            text,
    telefono          text,
    politica_id       bigint REFERENCES politicas_privacidad(id),
    version_politica  text,
    creado_en         timestamptz NOT NULL DEFAULT now(),
    actualizado_en    timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE perfiles ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS perfiles_select_propio ON perfiles;
CREATE POLICY perfiles_select_propio ON perfiles
    FOR SELECT TO authenticated
    USING (id = (SELECT auth.uid()));

DROP POLICY IF EXISTS perfiles_update_propio ON perfiles;
CREATE POLICY perfiles_update_propio ON perfiles
    FOR UPDATE TO authenticated
    USING (id = (SELECT auth.uid()))
    WITH CHECK (id = (SELECT auth.uid()));


CREATE TABLE IF NOT EXISTS motos_usuario (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  uuid NOT NULL REFERENCES perfiles(id) ON DELETE CASCADE,
    marca       text,
    modelo      text,
    placa       text,
    anio        integer CHECK (anio BETWEEN 1950 AND 2100),
    creado_en   timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS motos_usuario_usuario_id_idx ON motos_usuario (usuario_id);

ALTER TABLE motos_usuario ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS motos_usuario_propias ON motos_usuario;
CREATE POLICY motos_usuario_propias ON motos_usuario
    FOR ALL TO authenticated
    USING (usuario_id = (SELECT auth.uid()))
    WITH CHECK (usuario_id = (SELECT auth.uid()));


-- GRANTs: anon nada; authenticated lo justo (RLS igual filtra por fila).
-- perfiles: sin INSERT (lo crea el trigger) ni DELETE (cae por el CASCADE
-- al borrar la cuenta); UPDATE solo de columnas que el motero puede editar.
REVOKE ALL ON perfiles, motos_usuario FROM anon;
REVOKE ALL ON perfiles, motos_usuario FROM authenticated;
GRANT SELECT ON perfiles TO authenticated;
GRANT UPDATE (nombre, telefono, actualizado_en) ON perfiles TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON motos_usuario TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON perfiles, motos_usuario TO service_role;


-- Trigger: al crear una cuenta en auth.users, crea su fila en perfiles.
-- SECURITY DEFINER porque el que inserta en auth.users es el servicio de
-- Auth, no el motero; search_path vacío y nombres calificados para que no
-- se le pueda colar un objeto con el mismo nombre en otro schema.
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_politica_id bigint;
    v_version     text;
BEGIN
    IF NEW.raw_user_meta_data ->> 'acepta_politica' = 'true' THEN
        SELECT p.id, p.version
          INTO v_politica_id, v_version
          FROM public.politicas_privacidad p
         WHERE p.vigente_hasta IS NULL
         LIMIT 1;
    END IF;

    INSERT INTO public.perfiles (id, nombre, telefono, politica_id, version_politica)
    VALUES (
        NEW.id,
        NULLIF(left(btrim(NEW.raw_user_meta_data ->> 'nombre'), 120), ''),
        NULLIF(left(btrim(NEW.raw_user_meta_data ->> 'telefono'), 20), ''),
        v_politica_id,
        v_version
    );
    RETURN NEW;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.handle_new_user() FROM PUBLIC, anon, authenticated;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();
