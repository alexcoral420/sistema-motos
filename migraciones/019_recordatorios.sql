-- Recordatorios de vencimiento de SOAT y revisión técnico-mecánica por
-- notificación push (Web Push). Fase 1: modo anónimo, sin cuenta.
--
-- Quien activa un recordatorio recibe un token secreto (se guarda en el
-- localStorage del dispositivo). Con él podrá editar/borrar su recordatorio
-- sin login y, más adelante, "reclamarlo" desde una cuenta. Aquí se guarda
-- solo su SHA-256 (token_hash): si alguien leyera la tabla, no obtendría
-- tokens usables.
--
-- suscripcion es el PushSubscription del navegador: {endpoint, keys:
-- {p256dh, auth}}. El servicio valida la forma y que el endpoint sea de un
-- servicio de push conocido (el servidor le hará POST en la Fase 2).
--
-- La placa + la suscripción son datos personales (Ley 1581): cada registro
-- guarda la versión de la política de privacidad que se aceptó, igual que
-- leads_chat.

CREATE TABLE IF NOT EXISTS recordatorios (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash        TEXT NOT NULL UNIQUE,
    suscripcion       JSONB NOT NULL,
    fecha_soat        DATE,
    fecha_tecno       DATE,
    placa             TEXT,
    politica_id       BIGINT REFERENCES politicas_privacidad(id),
    version_politica  TEXT,
    activo            BOOLEAN NOT NULL DEFAULT true,
    creado_en         TIMESTAMPTZ NOT NULL DEFAULT now(),
    actualizado_en    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT recordatorios_alguna_fecha
        CHECK (fecha_soat IS NOT NULL OR fecha_tecno IS NOT NULL)
);

-- Fase 2: al enviar, un 404/410 del servicio de push significa que la
-- suscripción murió; se desactivan los recordatorios con ese endpoint.
CREATE INDEX IF NOT EXISTS idx_recordatorios_endpoint
    ON recordatorios ((suscripcion->>'endpoint'));

-- Fase 2: el envío diario busca vencimientos próximos entre los activos.
CREATE INDEX IF NOT EXISTS idx_recordatorios_soat
    ON recordatorios (fecha_soat) WHERE activo;
CREATE INDEX IF NOT EXISTS idx_recordatorios_tecno
    ON recordatorios (fecha_tecno) WHERE activo;

ALTER TABLE recordatorios ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON recordatorios FROM anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON recordatorios TO service_role;
