-- 030_leads_seguimiento.sql
--
-- Seguimiento de los leads por su asesor (/admin/leads).
--
-- Hasta aqui un lead tomado solo podia cerrarse (contactado | descartado).
-- Ahora el asesor lo lleva por etapas, anota lo que va pasando y programa
-- cuando volver a contactarlo:
--
--   estado            nuevo -> tomado ("por contactar") -> primer_contacto
--                     -> segundo_contacto -> cita_pendiente
--                     -> vendido | descartado
--   proximo_contacto  fecha (sin hora) en que el asesor quiere volver a
--                     hablar con el cliente. Nula si no programo nada o si
--                     el lead ya se cerro.
--   leads_notas       la linea de tiempo del lead: las notas del asesor
--                     (texto simple) y un renglon automatico por cada
--                     cambio de estado o de fecha. Solo se agrega: no hay
--                     UPDATE ni DELETE para nadie.
--
-- 'contactado' sigue PERMITIDO en el check aunque el codigo nuevo ya no lo
-- escribe: asi esta migracion es solo aditiva y el codigo que este en
-- produccion al aplicarla no se rompe. El codigo nuevo lo lee como
-- 'primer_contacto'.
--
-- ORDEN DE DESPLIEGUE: aplicar ANTES de desplegar el codigo (despues de
-- la 029).

alter table leads_chat add column if not exists proximo_contacto date;

alter table leads_chat drop constraint if exists leads_chat_estado_valido;
alter table leads_chat
    add constraint leads_chat_estado_valido
    check (estado in ('nuevo', 'tomado', 'primer_contacto', 'segundo_contacto',
                      'cita_pendiente', 'vendido', 'descartado', 'contactado'));

-- "Que tengo para hoy": los leads de un asesor con fecha programada.
create index if not exists leads_chat_seguimiento_idx
    on leads_chat (asesor_id, proximo_contacto)
    where proximo_contacto is not null;

create table if not exists leads_notas (
    id              bigint generated by default as identity primary key,
    lead_id         bigint not null references leads_chat(id) on delete cascade,
    created_at      timestamptz not null default now(),
    -- Quien la escribio, y su nombre congelado como texto (igual que en
    -- ventas y en leads_chat.asesor_nombre): el historial sigue legible si
    -- el usuario cambia de nombre o se borra.
    usuario_id      bigint references usuarios(id) on delete set null,
    usuario_nombre  text,
    -- 'nota'   lo que escribio el asesor
    -- 'evento' renglon automatico: cambio de estado o de fecha
    tipo            text not null default 'nota',
    texto           text not null,
    constraint leads_notas_tipo_valido check (tipo in ('nota', 'evento')),
    constraint leads_notas_texto_acotado check (char_length(texto) between 1 and 1000)
);

create index if not exists leads_notas_lead_idx on leads_notas (lead_id, created_at desc);

-- Mismo patron que el resto: RLS activado sin politicas, solo service_role.
-- Sin UPDATE ni DELETE: una nota no se edita ni se borra (el borrado en
-- cascada al eliminar el lead no pasa por estos permisos).
alter table leads_notas enable row level security;

revoke all on leads_notas from anon;
revoke all on leads_notas from authenticated;
-- Supabase le da ALL a service_role por defecto en las tablas nuevas:
-- se quita primero para que de verdad quede en solo lectura e insercion.
revoke all on leads_notas from service_role;
grant select, insert on leads_notas to service_role;

notify pgrst, 'reload schema';
