-- Avisos ya enviados de cada recordatorio (Fase 3: envío automático).
--
-- El job diario manda, por cada recordatorio y tipo (SOAT / tecno), un
-- aviso por umbral (30, 15, 7, 1 días antes del vencimiento). Esta tabla
-- registra cuáles ya salieron; la UNIQUE garantiza que un mismo umbral no
-- se mande dos veces aunque el job corra repetido o en paralelo.
--
-- Solo se registra un envío exitoso: si el push falla por algo pasajero
-- (429, 5xx, red), la siguiente corrida lo reintenta.

CREATE TABLE IF NOT EXISTS recordatorios_avisos (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recordatorio_id  BIGINT NOT NULL REFERENCES recordatorios(id) ON DELETE CASCADE,
    tipo             TEXT NOT NULL CHECK (tipo IN ('soat', 'tecno')),
    umbral           INTEGER NOT NULL CHECK (umbral > 0),
    enviado_en       TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT recordatorios_avisos_unico UNIQUE (recordatorio_id, tipo, umbral)
);

ALTER TABLE recordatorios_avisos ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON recordatorios_avisos FROM anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON recordatorios_avisos TO service_role;
