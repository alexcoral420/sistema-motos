-- "Mi espacio" del motero: alertas por usuario (Fase A) + sus dispositivos.
--
-- Modelo genérico: una alerta es de un tipo (soat, tecno, credito, aceite...)
-- y se dispara por fecha o por km. Fase A usa solo la de crédito: modo
-- 'fecha', recurrencia 'mensual', umbrales 3 y 1 días antes. Las columnas de
-- km quedan creadas (nullable) para no necesitar otra migración después.
--
-- Igual que perfiles/motos_usuario (021): el motero las consulta con la
-- llave anon + su JWT, así que RLS es la barrera real. El envío (Fase B)
-- correrá con service_role.
--
-- Recurrencia: fecha_objetivo es el ancla que puso el motero (su próxima
-- cuota) y no se reescribe al pasar cada mes. La ocurrencia de cada ciclo
-- se calcula (alertas_motero.proxima_ocurrencia); así una cuota del 31 no
-- queda corrida al 28 para siempre después de febrero.


-- ---------- dispositivos: suscripciones Web Push del motero ----------
-- suscripcion la valida y reconstruye el servidor antes de guardarla
-- (app/seguridad/suscripcion_push.py: endpoint https de un servicio de push
-- conocido, para que el envío no sea un vector de SSRF).
-- endpoint se deriva de la suscripción: con UNIQUE (usuario_id, endpoint),
-- volver a activar en el mismo navegador actualiza la fila en vez de
-- duplicarla.

CREATE TABLE IF NOT EXISTS dispositivos (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id   uuid NOT NULL REFERENCES perfiles(id) ON DELETE CASCADE,
    suscripcion  jsonb NOT NULL,
    endpoint     text GENERATED ALWAYS AS (suscripcion ->> 'endpoint') STORED,
    activo       boolean NOT NULL DEFAULT true,
    creado_en    timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT dispositivos_usuario_endpoint_unico UNIQUE (usuario_id, endpoint),
    CONSTRAINT dispositivos_con_endpoint CHECK (suscripcion ? 'endpoint')
);

-- Fase B: un 404/410 del servicio de push desactiva ese endpoint.
CREATE INDEX IF NOT EXISTS dispositivos_endpoint_idx ON dispositivos (endpoint);

ALTER TABLE dispositivos ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS dispositivos_propios ON dispositivos;
CREATE POLICY dispositivos_propios ON dispositivos
    FOR ALL TO authenticated
    USING (usuario_id = (SELECT auth.uid()))
    WITH CHECK (usuario_id = (SELECT auth.uid()));


-- ---------- alertas ----------

CREATE TABLE IF NOT EXISTS alertas (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id       uuid NOT NULL REFERENCES perfiles(id) ON DELETE CASCADE,
    moto_usuario_id  bigint REFERENCES motos_usuario(id) ON DELETE CASCADE,
    tipo             text NOT NULL
                     CHECK (tipo IN ('soat', 'tecno', 'credito', 'aceite', 'frenos', 'kit_arrastre', 'otro')),
    modo             text NOT NULL CHECK (modo IN ('fecha', 'km')),
    fecha_objetivo   date,
    recurrencia      text NOT NULL DEFAULT 'ninguna'
                     CHECK (recurrencia IN ('ninguna', 'mensual', 'anual')),
    umbrales_dias    integer[],
    -- Modo km (fases siguientes): sin reglas todavía.
    intervalo_km     integer CHECK (intervalo_km > 0),
    km_base          integer CHECK (km_base >= 0),
    umbrales_km      integer[],
    activo           boolean NOT NULL DEFAULT true,
    creado_en        timestamptz NOT NULL DEFAULT now(),
    actualizado_en   timestamptz NOT NULL DEFAULT now(),

    -- Una alerta por fecha necesita fecha y umbrales.
    CONSTRAINT alertas_fecha_completa CHECK (
        modo <> 'fecha' OR (fecha_objetivo IS NOT NULL AND umbrales_dias IS NOT NULL)
    ),
    -- Umbrales: de 1 a 5 valores, sin nulos, entre 0 y 365 días.
    CONSTRAINT alertas_umbrales_dias_validos CHECK (
        umbrales_dias IS NULL OR (
            cardinality(umbrales_dias) BETWEEN 1 AND 5
            AND array_position(umbrales_dias, NULL) IS NULL
            AND 0 <= ALL (umbrales_dias)
            AND 365 >= ALL (umbrales_dias)
        )
    )
);

CREATE INDEX IF NOT EXISTS alertas_usuario_id_idx ON alertas (usuario_id);
CREATE INDEX IF NOT EXISTS alertas_moto_usuario_id_idx ON alertas (moto_usuario_id);
-- Fase B: el envío diario recorre las alertas por fecha activas.
CREATE INDEX IF NOT EXISTS alertas_fecha_activas_idx
    ON alertas (fecha_objetivo) WHERE activo AND modo = 'fecha';

ALTER TABLE alertas ENABLE ROW LEVEL SECURITY;

-- WITH CHECK también exige que la moto (si hay) sea del motero. La FK sola
-- no alcanza: se verifica sin RLS, así que sin esta condición un motero
-- podría colgar una alerta del id de una moto ajena.
DROP POLICY IF EXISTS alertas_propias ON alertas;
CREATE POLICY alertas_propias ON alertas
    FOR ALL TO authenticated
    USING (usuario_id = (SELECT auth.uid()))
    WITH CHECK (
        usuario_id = (SELECT auth.uid())
        AND (
            moto_usuario_id IS NULL
            OR EXISTS (
                SELECT 1 FROM motos_usuario m
                 WHERE m.id = moto_usuario_id
                   AND m.usuario_id = (SELECT auth.uid())
            )
        )
    );


-- ---------- alertas_avisos: qué aviso ya salió (Fase B) ----------
-- ciclo identifica la ocurrencia ('YYYY-MM' en las mensuales); el UNIQUE
-- impide mandar dos veces el mismo umbral del mismo ciclo. Las escribe y
-- lee solo el envío (service_role): el motero no tiene grants aquí.

CREATE TABLE IF NOT EXISTS alertas_avisos (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alerta_id   bigint NOT NULL REFERENCES alertas(id) ON DELETE CASCADE,
    ciclo       text NOT NULL,
    umbral      integer NOT NULL,
    enviado_en  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT alertas_avisos_unico UNIQUE (alerta_id, ciclo, umbral)
);

ALTER TABLE alertas_avisos ENABLE ROW LEVEL SECURITY;


-- ---------- GRANTs ----------
-- anon nada; authenticated lo justo (RLS igual filtra por fila).
-- dispositivos: UPDATE incluye usuario_id porque el upsert de PostgREST
-- (ON CONFLICT DO UPDATE) reescribe todas las columnas del payload; el
-- WITH CHECK impide ponerle otro valor que auth.uid().
-- alertas: sin UPDATE de usuario_id, tipo ni modo.
REVOKE ALL ON dispositivos, alertas, alertas_avisos FROM anon;
REVOKE ALL ON dispositivos, alertas, alertas_avisos FROM authenticated;

GRANT SELECT, INSERT, DELETE ON dispositivos TO authenticated;
GRANT UPDATE (usuario_id, suscripcion, activo) ON dispositivos TO authenticated;

GRANT SELECT, INSERT, DELETE ON alertas TO authenticated;
GRANT UPDATE (moto_usuario_id, fecha_objetivo, recurrencia, umbrales_dias,
              intervalo_km, km_base, umbrales_km, activo, actualizado_en)
    ON alertas TO authenticated;

GRANT SELECT, INSERT, UPDATE, DELETE ON dispositivos, alertas, alertas_avisos TO service_role;
